_cache: Dict[str, dict] = {}


def now():
    return time.time()


def load(pid: str) -> dict:
    if not pid.isalnum():
        raise HTTPException(404, "Unknown participant session")
    if pid in _cache:
        return _cache[pid]
    path = DATA_DIR / f"{pid}.json"
    if not path.exists():
        raise HTTPException(404, "Unknown participant session")
    _cache[pid] = json.loads(path.read_text())
    return _cache[pid]


def save(s: dict):
    _cache[s["pid"]] = s
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    tmp = DATA_DIR / f".{s['pid']}.tmp"
    tmp.write_text(json.dumps(s, indent=1))
    tmp.replace(DATA_DIR / f"{s['pid']}.json")


def log_event(s, task_idx, etype, data=None):
    s["events"].append({"at": now(), "task": task_idx, "type": etype, "data": data or {}})


