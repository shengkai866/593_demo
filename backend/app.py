def materials_for(task):
    sc = scen(task)
    mats = [{"id": f"file:{name}", "kind": "file", "name": name} for name in sc["files"]]
    for m in sc["materials"]:
        mats.append({"id": f"material:{m['name']}", "kind": "material", "name": m["name"]})
    if sc["assignment"] and sc["assignment_source"] in ("example", "ai"):
        mats.append({"id": "instructions", "kind": "doc",
                     "name": "Task description" + (" (AI-generated)" if sc["assignment_source"] == "ai" else "")})
    mats.append({"id": "output", "kind": "output", "name": f"Latest program output (python {sc['entry']})"})
    mats.append({"id": "checks", "kind": "checks", "name": "Latest check results"})
    return mats


def all_checks(task):
    return scen(task)["checks"] + [dict(c, author="You", kind="call") for c in task["custom_checks"]]


def build_ai_context(task) -> str:
    """Exactly the text that is sent to the AI (also shown to the learner)."""
    sc = scen(task)
    req = task["request"] or {}
    selected = set(task["context_materials"])
    files = replay(task)
    parts = [f"STUDENT GOALS: {', '.join(task['goal']['goals']) or 'not set'}"]
    if task["goal"].get("text"):
        parts.append(f"GOAL IN THEIR WORDS: {task['goal']['text']}")
    if req.get("problem"):
        parts.append(f"PROBLEM DESCRIPTION: {req['problem']}")
    if req.get("knowledge"):
        parts.append(f"STUDENT BACKGROUND: {req['knowledge']}")
    if req.get("rules"):
        parts.append(f"COURSE RULES: {req['rules']}")
    if "instructions" in selected and sc["assignment"]:
        parts.append(f"TASK DESCRIPTION: {sc['assignment']}")
    for m in sc["materials"]:
        if f"material:{m['name']}" in selected:
            parts.append(f"LEARNING MATERIAL {m['name']}:\n{m['text'][:20000]}")
    ranges = req.get("ranges") or {}
    for name, text in files.items():
        if f"file:{name}" not in selected:
            continue
        lines = text.rstrip("\n").split("\n")
        rng = ranges.get(name)
        lo, hi = (rng if rng else (1, len(lines)))
        lo, hi = max(1, int(lo)), min(len(lines), int(hi))
        body = "\n".join(f"{i:>3} | {lines[i - 1]}" for i in range(lo, hi + 1))
        scope = "" if (lo, hi) == (1, len(lines)) else f" (lines {lo}-{hi} only)"
        parts.append(f"FILE {name}{scope} (current state: {state_label(task)}):\n{body}")
    if "output" in selected and task.get("latest_output"):
        o = task["latest_output"]
        parts.append(f"LATEST PROGRAM OUTPUT ({o['command']}):\n{(o['stdout'] + o['stderr']).strip() or '(no output)'}")
    if "checks" in selected and task["runs"]:
        last = task["runs"][-1]
        lines = [f"- {r['name']}: {r['call']} expected {r['expected']}, actual {r['actual']} -> {r['status'].upper()}"
                 for r in last["results"]]
        parts.append(f"LATEST CHECK RESULTS ({last['state']}):\n" + "\n".join(lines))
    return "\n\n".join(parts)


def proposal_view(task, p):
    files_now = replay(task)
    applied = set(applied_keys(task))
    hunks = []
    for h in p["change"]["hunks"]:
        key = (p["id"], h["id"])
        if key in applied:
            status = "applied"
            before = replay(task, exclude={key})[h["file"]]
            after = files_now[h["file"]]
        else:
            before = files_now.get(h["file"], "")
            try:
                after = apply_hunk(files_now, h)[h["file"]]
                status = "pending"
            except Conflict:
                after = before
                status = "conflict"
        hunks.append({"id": h["id"], "file": h["file"], "label": h["label"], "status": status,
                      "rows": diff_rows(before, after)})
    pv = {k: v for k, v in p.items() if k not in ("kind", "verified")}
    pv["change"] = {k: v for k, v in p["change"].items() if k != "hunks"}
    pv["change"]["hunks"] = hunks
    pv["label"] = label_of(task, p["id"])
    pv["explanation_label"] = "AI explanation"
    pv["decision"] = task["decisions"].get(p["id"])
    return pv


def modified_lines(task, files):
    out = {}
    base = scen(task)["files"]
    for name, text in files.items():
        out[name] = sorted({r["b"] for r in diff_rows(base[name], text) if r["t"] == "add"})
    return out


COMPREHENSION_KEYS = ("localization", "root_cause", "fix_rationale")


def comprehension_view(task):
    """Omits `correct` (researcher-only), same as proposal_view omits `kind`."""
    comp = scen(task)["comprehension"]
    answer = task["comprehension"]
    return {
        "questions": {k: {"prompt": comp[k]["prompt"], "code_options": bool(comp[k].get("code_options")),
                          "options": [{"id": o["id"], "text": o["text"]} for o in comp[k]["options"]]}
                     for k in COMPREHENSION_KEYS},
        "r5_explanation": comp.get("r5_explanation"),
        "r6_explanation": comp.get("r6_explanation"),
        "r6_fix": comp.get("r6_fix"),
        "answered": answer is not None,
        "answers": (answer or {}).get("answers"),
    }


def task_view(s, idx):
    task = s["tasks"][idx]
    base = {"index": idx, "total": len(s["tasks"]), "ai_enabled": ai.ENABLED,
            "examples_left": len(s["example_order"]) > 0}
    if not task.get("scenario"):
        return {**base, "scenario": None}
    sc = scen(task)
    files = replay(task)
    return {
        **base,
        "scenario": {
            "title": sc["title"], "assignment": sc["assignment"], "assignment_source": sc["assignment_source"],
            "entry": sc["entry"], "knowledge": sc["knowledge"], "rules": sc["rules"],
            "problem_hint": sc["problem_hint"], "source": sc["source"], "checks_source": sc["checks_source"],
            "setup_warning": sc.get("setup_warning"), "example": sc.get("example"),
        },
        "files": files,
        "file_order": list(sc["files"].keys()),
        "docs": [{"name": m["name"], "text": m["text"]} for m in sc["materials"]],
        "functions": sc["functions"],
        "modified_lines": modified_lines(task, files),
        "state_label": state_label(task),
        "materials": materials_for(task),
        "context_materials": task["context_materials"],
        "ai_context": build_ai_context(task) if task["request"] else None,
        "goal": task["goal"],
        "goal_history": task["goal_history"],
        "request": task["request"],
        "generation": task.get("generation"),
        "proposals": [proposal_view(task, proposal(task, pid_)) for pid_ in task["proposal_order"]]
        if task["request"] else [],
        "comprehension": comprehension_view(task) if task["request"] and sc.get("comprehension") else None,
        "applied": [
            {"app_id": a["app_id"], "proposal_id": a["proposal_id"], "label": label_of(task, a["proposal_id"]),
             "at": a["at"], "hunks": [{"id": h, "label": hunk(task, a["proposal_id"], h)["label"]} for h in a["hunk_ids"]]}
            for a in task["applied"]
        ],
        "history": task["history"],
        "checks": [{"id": c["id"], "name": c["name"], "author": c.get("author", "Course staff"),
                    "call": runner.check_call(c), "expected": runner.check_expected(c)} for c in all_checks(task)],
        "runs": task["runs"][-10:],
        "latest_output": task.get("latest_output"),
        "conversation": task["conversation"],
        "office_hours": task.get("office_hours"),
        "work_done": task.get("work_done", False),
    }


