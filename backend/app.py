@app.post("/api/sessions/{pid}/tasks/{idx}/finish")
def post_finish(pid: str, idx: int):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        sc = scen(task)
        if sc.get("comprehension") and task["comprehension"] is None:
            raise HTTPException(400, "Answer the comprehension questions before finishing this task")
        res = runner.run_checks(replay(task), all_checks(task))
        task["work_done"] = True
        task["finished_at"] = now()
        given = [r for r in res["results"] if r["author"] != "You"]
        task["final_state"] = {"state": state_label(task),
                               "all_pass": bool(given) and all(r["status"] == "pass" for r in given),
                               "results": [(r["id"], r["status"]) for r in res["results"]]}
        log_event(s, idx, "task_finished", task["final_state"])
        save(s)
        return session_summary(s)


