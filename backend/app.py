@app.post("/api/sessions/{pid}/tasks/{idx}/run")
def post_run(pid: str, idx: int):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        sc = scen(task)
        files = replay(task)
        res = runner.run_checks(files, all_checks(task))
        sig = code_signature(files)
        label = state_label(task)
        # Repeated-failure detection: the same check failing under different code states.
        for r in res["results"]:
            states = []
            for prev in task["runs"]:
                pr = next((x for x in prev["results"] if x["id"] == r["id"]), None)
                if pr and pr["status"] == "fail" and prev["signature"] != sig and prev["state"] not in states:
                    states.append(prev["state"])
            r["failed_before_under"] = states if r["status"] == "fail" else []
        task["runs"].append({"run_id": uuid.uuid4().hex[:8], "at": now(), "state": label, "signature": sig,
                             "error": res["error"], "results": res["results"]})
        task["latest_output"] = runner.run_program(files, sc["entry"])
        passed = sum(r["status"] == "pass" for r in res["results"])
        add_history(task, "run", f"Ran checks on: {label} - {passed}/{len(res['results'])} passed")
        log_event(s, idx, "checks_run", {"state": label, "passed": passed, "total": len(res["results"]),
                                         "failed": [r["id"] for r in res["results"] if r["status"] == "fail"]})
        save(s)
        return task_view(s, idx)


@app.post("/api/sessions/{pid}/tasks/{idx}/simulate")
def post_simulate(pid: str, idx: int, body: SimulateIn):
    """Run checks as if a change were applied, without changing the code."""
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        p = proposal(task, body.proposal_id)
        files_now = replay(task)
        checks = all_checks(task)
        before = runner.run_checks(files_now, checks)
        files = files_now
        already = set(applied_keys(task))
        try:
            for h in p["change"]["hunks"]:
                if h["id"] in body.hunk_ids and (p["id"], h["id"]) not in already:
                    files = apply_hunk(files, h)
        except Conflict as e:
            raise HTTPException(409, str(e))
        after = runner.run_checks(files, checks)
        log_event(s, idx, "change_simulated", {"proposal": p["id"], "kind": p["kind"], "hunks": body.hunk_ids})
        save(s)
        rows = [{"name": b["name"], "call": b["call"], "expected": b["expected"],
                 "before": b["actual"], "before_status": b["status"],
                 "after": a["actual"], "after_status": a["status"]}
                for b, a in zip(before["results"], after["results"])]
        return {"rows": rows, "error": after["error"] or before["error"]}


@app.post("/api/sessions/{pid}/tasks/{idx}/checks")
def post_check(pid: str, idx: int, body: CheckIn):
    try:
        args = json.loads(body.args)
        expected = json.loads(body.expected)
    except json.JSONDecodeError as e:
        raise HTTPException(400, f"Arguments and expected value must be valid JSON: {e.msg}")
    if not isinstance(args, list):
        raise HTTPException(400, "Arguments must be a list, e.g. [[1, 2, 3], 4]")
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        funcs = scen(task)["functions"]
        target = next((f for f in funcs if f"{f['module']}.{f['function']}" == body.function), None) \
            or (funcs[0] if funcs else None)
        if not target:
            raise HTTPException(400, "No function found to check in the uploaded code")
        check = {"id": "u" + uuid.uuid4().hex[:6], "name": body.name.strip() or "My check",
                 "module": target["module"], "function": target["function"], "args": args, "expected": expected}
        task["custom_checks"].append(check)
        add_history(task, "check", f"Added check: {check['name']}")
        log_event(s, idx, "check_added", check)
        save(s)
        return task_view(s, idx)


