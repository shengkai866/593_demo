@app.post("/api/sessions/{pid}/tasks/{idx}/comprehension")
def post_comprehension(pid: str, idx: int, body: ComprehensionIn):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        comp = scen(task).get("comprehension")
        if not comp:
            raise HTTPException(400, "No comprehension questions are available for this task")
        if task["comprehension"] is not None:
            raise HTTPException(400, "The comprehension questions for this task were already answered")
        missing = [k for k in COMPREHENSION_KEYS if k not in body.answers]
        if missing:
            raise HTTPException(400, f"Missing answers for: {', '.join(missing)}")
        for k in COMPREHENSION_KEYS:
            if body.answers[k] not in {o["id"] for o in comp[k]["options"]}:
                raise HTTPException(400, f"Unknown option for {k}")
        correct = {k: int(body.answers[k] == comp[k]["correct"]) for k in COMPREHENSION_KEYS}
        task["comprehension"] = {"at": now(), "answers": dict(body.answers), "correct": correct}
        add_history(task, "comprehension", "Answered the comprehension questions")
        log_event(s, idx, "comprehension_submitted", {"answers": body.answers, "correct": correct})
        save(s)
        return task_view(s, idx)


