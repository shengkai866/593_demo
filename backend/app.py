def numbered(files: dict, only=None) -> str:
    parts = []
    for name, text in files.items():
        if only is not None and name not in only:
            continue
        lines = text.rstrip("\n").split("\n")
        parts.append(f"FILE {name}:\n" + "\n".join(f"{i:>3} | {l}" for i, l in enumerate(lines, 1)))
    return "\n\n".join(parts)


def materials_text(materials, limit=20000) -> str:
    return "\n\n".join(f"MATERIAL {m['name']}:\n{m['text'][:limit]}" for m in materials)


def build_comprehension(sc: dict) -> Optional[dict]:
    """R5 (code localization) and R6 (root cause / fix rationale) questions from the study protocol,
    scored 0/1 against the protocol's answer key. Options keep the protocol's A-D order and ids.
    The explanation texts shown with the questions are taken from the task's single proposal, so the
    questions quote exactly what the AI panel shows. Only built-in tasks have questions."""
    questions = sc.get("questions")
    proposals = sc.get("proposals") or []
    if not questions or not proposals:
        return None
    p = proposals[0]
    comp = copy.deepcopy(questions)
    comp.update(proposal_id=p["id"], r5_explanation=p.get("code_explanation"),
                r6_explanation=p["why_fails"], r6_fix=p["change"]["why"])
    return comp


def scenario_from_example(example_id: str) -> dict:
    sc = copy.deepcopy(SCENARIOS[example_id])
    for c in sc["checks"]:
        c.update(kind="call", module=sc["module"], function=sc["function"], author="Course staff")
    sc.update(source="example", materials=[], assignment_source="example", checks_source="course",
              test_files=[], functions=uploads.functions(sc["files"]))
    sc["comprehension"] = build_comprehension(sc)
    return sc


def validate_ai_checks(raw, funcs) -> list:
    known = {(f["module"], f["function"]) for f in funcs}
    checks = []
    for c in raw or []:
        try:
            args = json.loads(c["args_json"])
            expected = json.loads(c["expected_json"])
        except (json.JSONDecodeError, KeyError, TypeError):
            continue
        if not isinstance(args, list) or (c["module"], c["function"]) not in known:
            continue
        checks.append({"id": f"a{len(checks) + 1}", "kind": "call", "name": c["name"], "module": c["module"],
                       "function": c["function"], "args": args, "expected": expected,
                       "author": "AI-generated (from the assignment)"})
    return checks[:8]


def scenario_from_upload(files_in: list, entry: Optional[str]) -> dict:
    up = uploads.classify(files_in)
    code, materials, tests = up["code"], up["materials"], up["tests"]
    funcs = uploads.functions(code)
    checks = uploads.test_checks(code, tests)
    sc = {
        "id": "upload", "source": "upload", "files": code, "materials": materials, "test_files": tests,
        "functions": funcs, "entry": entry if entry in code else uploads.choose_entry(code),
        "title": next((n for n in code if n not in tests), "Your code"),
        "assignment": "", "assignment_source": "materials" if materials else "none",
        "checks": checks, "checks_source": "tests" if checks else "none",
        "knowledge": "", "rules": "", "problem_hint": "the result is not what I expected",
        "proposals": None, "comprehension": None, "explain_again": None, "new_approach": None,
    }
    need_assignment = not materials
    need_checks = not checks and bool(funcs)
    if ai.ENABLED:
        context = numbered(code) + ("\n\n" + materials_text(materials) if materials else "")
        context += "\n\nTOP-LEVEL FUNCTIONS: " + ", ".join(f"{f['module']}.{f['signature']}" for f in funcs)
        prompt = ai.TASK_INFO_PROMPT.format(
            context=context,
            assignment_instruction=(
                "2-4 sentences describing what the code is supposed to do (the intended behavior), inferred from the "
                "code, names, and comments. Write it like an assignment description."
                if need_assignment else
                "a 1-3 sentence summary of the uploaded assignment materials (the intended behavior)."),
            checks_instruction=(
                "4-6 checks covering normal cases and edge cases of the main function(s)."
                if need_checks else "return an empty array (the student uploaded their own tests)."),
        )
        data, err = ai.safe_json(prompt, ai.TASK_INFO_SCHEMA)
        if data:
            sc["title"] = data.get("title") or sc["title"]
            sc["assignment"] = data.get("assignment", "")
            sc["assignment_source"] = "ai" if need_assignment else "materials"
            if need_checks:
                sc["checks"] = validate_ai_checks(data.get("checks"), funcs)
                sc["checks_source"] = "ai" if sc["checks"] else "none"
        else:
            sc["setup_warning"] = err
    elif need_assignment:
        sc["assignment_source"] = "none"
    return sc


def validate_proposals(raw: dict, files: dict) -> list:
    """The AI returns ONE proposal (explanation + fix). Returns [proposal] or [] if its edit doesn't apply."""
    p = raw.get("proposal")
    if not p:
        return []
    hunks = []
    trial = dict(files)
    for h in p["change"]["hunks"]:
        h = {"id": f"h{len(hunks) + 1}", "file": h["file"], "label": h["label"] or "Edit",
             "old": h["old"].rstrip("\n"), "new": h["new"].rstrip("\n")}
        try:
            trial = apply_hunk(trial, h)
        except Conflict:
            continue
        hunks.append(h)
    if not hunks:
        return []

    def valid_refs(refs):
        return [r for r in refs or [] if REF_RE.match(r) and r.split(":")[0] in files]

    first = hunks[0]
    refs = valid_refs(p.get("refs")) or \
        [f"{first['file']}:{next((n for n, l in enumerate(files[first['file']].split(chr(10)), 1) if l == first['old'].split(chr(10))[0]), 1)}"]
    return [{
        "id": "p1", "kind": "necessary", "summary": p["summary"],
        "code_refs": valid_refs(p.get("code_refs")), "code_explanation": p["code_explanation"],
        "refs": refs, "why_fails": p["why_fails"],
        "current_behavior": p["current_behavior"], "correct_behavior": p["correct_behavior"],
        "change": {"why": p["change"]["why"], "claimed_effect": p["change"]["claimed_effect"], "hunks": hunks},
    }]


