@app.post("/api/sessions/{pid}/tasks/{idx}/apply")
def post_apply(pid: str, idx: int, body: ApplyIn):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        p = proposal(task, body.proposal_id)
        already = set(applied_keys(task))
        hunk_ids = [h["id"] for h in p["change"]["hunks"]
                    if h["id"] in body.hunk_ids and (p["id"], h["id"]) not in already]
        if not hunk_ids:
            raise HTTPException(400, "Select at least one part of the change that is not already applied")
        files = replay(task)
        try:
            for hid in hunk_ids:
                files = apply_hunk(files, hunk(task, p["id"], hid))
        except Conflict as e:
            raise HTTPException(409, str(e))
        task["applied"].append({"app_id": uuid.uuid4().hex[:8], "proposal_id": p["id"], "hunk_ids": hunk_ids,
                                "at": now()})
        task["decisions"].pop(p["id"], None)
        total = len(p["change"]["hunks"])
        add_history(task, "apply", f"Applied {label_of(task, p['id'])}"
                    + ("" if len(hunk_ids) == total else f" ({len(hunk_ids)} of {total} parts)"))
        log_event(s, idx, "change_applied", {"proposal": p["id"], "kind": p["kind"], "hunks": hunk_ids})
        save(s)
        return task_view(s, idx)


@app.post("/api/sessions/{pid}/tasks/{idx}/undo")
def post_undo(pid: str, idx: int, body: UndoIn):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        backup = copy.deepcopy(task["applied"])
        app_ = next((a for a in task["applied"] if a["app_id"] == body.app_id), None)
        if not app_:
            raise HTTPException(404, "That change is not currently applied")
        if body.hunk_id:
            app_["hunk_ids"] = [h for h in app_["hunk_ids"] if h != body.hunk_id]
            removed = [body.hunk_id]
        else:
            removed = list(app_["hunk_ids"])
            app_["hunk_ids"] = []
        if not app_["hunk_ids"]:
            task["applied"] = [a for a in task["applied"] if a["app_id"] != body.app_id]
        try:
            replay(task)
        except Conflict:
            task["applied"] = backup
            raise HTTPException(409, "Undo the changes that depend on this one first")
        add_history(task, "undo", f"Undid {label_of(task, app_['proposal_id'])}"
                    + (f" (part: {hunk(task, app_['proposal_id'], body.hunk_id)['label']})" if body.hunk_id else ""))
        log_event(s, idx, "change_undone", {"proposal": app_["proposal_id"], "hunks": removed})
        save(s)
        return task_view(s, idx)


