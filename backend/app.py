class Conflict(Exception):
    pass


def scen(task):
    if not task.get("scenario"):
        raise HTTPException(400, "Set up this task first (upload files or choose an example)")
    return task["scenario"]


def proposals_of(task):
    return scen(task).get("proposals") or []


def proposal(task, proposal_id):
    for p in proposals_of(task):
        if p["id"] == proposal_id:
            return p
    raise HTTPException(404, "Unknown proposal")


def hunk(task, proposal_id, hunk_id):
    for h in proposal(task, proposal_id)["change"]["hunks"]:
        if h["id"] == hunk_id:
            return h
    raise HTTPException(404, "Unknown hunk")


def apply_hunk(files: dict, h: dict) -> dict:
    if h["file"] not in files:
        raise Conflict(f"{h['file']} does not exist")
    lines = files[h["file"]].split("\n")
    old = h["old"].split("\n")
    for i in range(len(lines) - len(old) + 1):
        if lines[i:i + len(old)] == old:
            out = dict(files)
            out[h["file"]] = "\n".join(lines[:i] + h["new"].split("\n") + lines[i + len(old):])
            return out
    raise Conflict(f"Could not find the original code for this change in {h['file']}")


def applied_keys(task, exclude=None):
    exclude = exclude or set()
    return [(a["proposal_id"], hid) for a in task["applied"] for hid in a["hunk_ids"]
            if (a["proposal_id"], hid) not in exclude]


def replay(task, exclude=None) -> dict:
    files = dict(scen(task)["files"])
    for pid_, hid in applied_keys(task, exclude):
        files = apply_hunk(files, hunk(task, pid_, hid))
    return files


def code_signature(files):
    return hashlib.sha1(json.dumps(files, sort_keys=True).encode()).hexdigest()[:10]


def diff_rows(before: str, after: str):
    a, b = before.split("\n"), after.split("\n")
    if a and a[-1] == "":
        a = a[:-1]
    if b and b[-1] == "":
        b = b[:-1]
    rows = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1):
                rows.append({"t": "same", "a": i1 + k + 1, "b": j1 + k + 1, "text": a[i1 + k]})
        else:
            for k in range(i1, i2):
                rows.append({"t": "del", "a": k + 1, "b": None, "text": a[k]})
            for k in range(j1, j2):
                rows.append({"t": "add", "a": None, "b": k + 1, "text": b[k]})
    return rows


def label_of(task, proposal_id):
    # Every task has exactly one explanation and one suggested change.
    return "Suggested change"


def state_label(task):
    if not task["applied"]:
        return "Original code (no changes applied)"
    return "Applied: " + ", ".join(dict.fromkeys(label_of(task, a["proposal_id"]) for a in task["applied"]))


def add_history(task, action, text):
    task["history"].append({"at": now(), "action": action, "text": text})


