def action_log(task) -> str:
    """Facts about what the learner actually did (used for the office-hours draft)."""
    lines = []
    req = task["request"] or {}
    if req.get("problem"):
        lines.append(f"Learner's problem description: {req['problem']}")
    for h in task["history"]:
        lines.append(f"- {h['text']}")
    if not task["runs"]:
        lines.append("- Has NOT run the checks yet")
    else:
        for r in task["runs"][-1]["results"]:
            if r["status"] == "fail":
                lines.append(f"- Latest run: {r['call']} expected {r['expected']}, got {r['actual']}")
    return "\n".join(lines)


def office_hours_template(task):
    sc = scen(task)
    out = [f"I'm working on {sc['title']}."]
    last = task["runs"][-1] if task["runs"] else None
    fails = [r for r in (last["results"] if last else []) if r["status"] == "fail"]
    if fails:
        r = fails[0]
        where = "the original code" if not last["state"].startswith("Applied") else f"my code ({last['state']})"
        out.append(f"When I ran the checks on {where}, {r['call']} returned {r['actual']} but I expected {r['expected']}.")
        if last["signature"] != code_signature(replay(task)):
            out.append("I have changed the code since that run.")
    elif (task["request"] or {}).get("problem"):
        out.append(f"My problem: {task['request']['problem']}")
    did = [h["text"] for h in task["history"] if h["action"] in ("apply", "undo", "reject", "run")]
    out.append(("So far I have: " + "; ".join(did[-4:]) + ".") if did
               else "I haven't changed the code or run the checks yet.")
    out.append("Could you help me understand why the result differs from what I expect, and which other cases I should check?")
    return " ".join(out)


def scripted_answer(task, mode, body: AskIn) -> str:
    sc = scen(task)
    if mode == "explain_again":
        return sc.get("explain_again") or ("(Scripted answer: the AI is not connected.) Pick one failing check and trace "
                                           "the code by hand for that input, writing down each variable after each line.")
    if mode == "new_approach":
        return sc.get("new_approach") or ("(Scripted answer: the AI is not connected.) Compare two inputs: one that works "
                                          "and one that fails. Trace both and find the first line where they behave differently.")
    if mode == "office_hours":
        return office_hours_template(task)
    p = proposal(task, body.proposal_id) if body.proposal_id else None
    if p:
        return (f"(Scripted answer: the AI is not connected.) This explanation focuses on "
                f"{', '.join('[' + r + ']' for r in p['refs'])}. {p['why_fails']}")
    return ("(Scripted answer: the AI is not connected.) Try tracing the failing check by hand, line by line, "
            "and compare the value returned with the expected value.")


