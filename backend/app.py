@app.post("/api/sessions/{pid}/tasks/{idx}/setup")
def post_setup(pid: str, idx: int, body: SetupIn):
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        if task.get("scenario"):
            raise HTTPException(400, "This task is already set up")
        examples = list(s["example_order"])
    if body.mode == "example":
        if not examples:
            raise HTTPException(400, "No example tasks left")
        sc = scenario_from_example(examples[0])
    elif body.mode == "upload":
        if STUDY_MODE:
            raise HTTPException(400, "Uploading your own code is disabled during this study. Use an example task.")
        try:
            sc = scenario_from_upload([f.model_dump() for f in body.files], body.entry)  # may call the AI
        except uploads.UploadError as e:
            raise HTTPException(400, str(e))
    else:
        raise HTTPException(400, "Unknown mode")
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        if body.mode == "example":
            s["example_order"].remove(sc["id"])
            order = [p["id"] for p in sc["proposals"]]
            random.shuffle(order)
            task["proposal_order"] = order
        task["scenario"] = sc
        task["started_at"] = now()
        log_event(s, idx, "task_setup", {
            "mode": body.mode, "scenario": sc["id"], "files": list(sc["files"]),
            "materials": [m["name"] for m in sc["materials"]], "checks_source": sc["checks_source"],
            "assignment_source": sc["assignment_source"], "proposal_order": task["proposal_order"]})
        save(s)
        return task_view(s, idx)


VALID_GOALS = {"understand", "fix"}


def generate_proposals(pid, idx):
    """Ask the AI for explanations + changes for uploaded code. Runs outside the lock."""
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        sc = scen(task)
        if sc["source"] != "upload" or sc.get("proposals"):
            return
        if not ai.ENABLED:
            task["generation"] = {"status": "unavailable",
                                  "message": "The AI is not connected, so explanations and proposed changes can't be "
                                             "generated for uploaded code. You can still view the code, run the "
                                             "program, and run or add checks."}
            save(s)
            return
        task["generation"] = {"status": "running"}
        files = replay(task)
        context = build_ai_context(task)
        if "FILE " not in context:  # the AI must see the code to propose edits
            context += "\n\n" + numbered(files)
        if sc["checks"]:
            res = runner.run_checks(files, sc["checks"])
            context += "\n\nCHECK RESULTS ON THE CURRENT CODE:\n" + "\n".join(
                f"- {r['name']}: {r['call']} expected {r['expected']}, actual {r['actual']} -> {r['status']}"
                for r in res["results"])
        save(s)
    prompt = ai.PROPOSALS_PROMPT.format(context=context)
    data, err = ai.safe_json(prompt, ai.PROPOSALS_SCHEMA)
    proposals = validate_proposals(data, files) if data else []
    if data and not proposals:
        data, err = ai.safe_json(prompt + "\n\nIMPORTANT: copy every `old` line exactly from the file, "
                                          "character for character.", ai.PROPOSALS_SCHEMA)
        proposals = validate_proposals(data, files) if data else []
        if not proposals and not err:
            err = "The AI's proposed edits didn't match the code."
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        sc = scen(task)
        if not proposals:
            task["generation"] = {"status": "failed", "message": err or "Generation failed."}
            log_event(s, idx, "generation_failed", {"error": err})
            save(s)
            return
        # Researcher-only: how each proposal actually changes the check results.
        for p in proposals:
            try:
                after = apply_all(files, p)
                p["verified"] = {"passes_before": count_pass(files, sc["checks"]),
                                 "passes_after": count_pass(after, sc["checks"]), "total": len(sc["checks"])}
            except Conflict:
                p["verified"] = None
        sc["proposals"] = proposals
        sc["comprehension"] = build_comprehension(sc)
        sc["explain_again"] = data.get("explain_again")
        sc["new_approach"] = data.get("new_approach")
        order = [p["id"] for p in proposals]
        random.shuffle(order)
        task["proposal_order"] = order
        task["generation"] = {"status": "done"}
        log_event(s, idx, "proposals_generated", {
            "order": order, "kinds": {p["id"]: p["kind"] for p in proposals},
            "verified": {p["id"]: p["verified"] for p in proposals}})
        save(s)


def apply_all(files, p):
    for h in p["change"]["hunks"]:
        files = apply_hunk(files, h)
    return files


def count_pass(files, checks):
    if not checks:
        return None
    return sum(r["status"] == "pass" for r in runner.run_checks(files, checks)["results"])


@app.post("/api/sessions/{pid}/tasks/{idx}/request")
def post_request(pid: str, idx: int, body: RequestIn):
    goals = [g for g in body.goals if g in VALID_GOALS]
    if not goals:
        raise HTTPException(400, "Choose at least one goal")
    with _lock:
        s = load(pid)
        task = get_task(s, idx)
        sc = scen(task)
        if task["latest_output"] is None:
            task["latest_output"] = runner.run_program(replay(task), sc["entry"])
        task["goal"] = {"goals": goals, "text": body.goal_text}
        task["goal_history"].append({"at": now(), "goals": goals, "text": body.goal_text, "source": "request"})
        task["request"] = {"at": now(), "problem": body.problem, "knowledge": body.knowledge, "rules": body.rules,
                           "ranges": body.ranges}
        valid = {m["id"] for m in materials_for(task)}
        task["context_materials"] = [m for m in body.materials if m in valid]
        add_history(task, "request", f"Sent request (goals: {', '.join(goals)})")
        log_event(s, idx, "request_sent", body.model_dump())
        save(s)
    generate_proposals(pid, idx)
    with _lock:
        return task_view(load(pid), idx)


